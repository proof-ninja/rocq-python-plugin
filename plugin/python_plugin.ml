(** Rocq の Extraction 言語 "Python" を、サードパーティのプラグインとして登録する。

    使い方:
      Declare ML Module "rocq-runtime.plugins.extraction".
      Declare ML Module "rocq-python-plugin.plugin".
      Extraction Language Python.
      Extraction "out.py" foo.

    処理の流れ:
      ml_ast --Convert--> mexpr --Pycert_translate.tr_prog (Rocq で検証)--> pystmt
             --Py_print--> Python のソース *)
open Extraction_plugin
open Miniml
open Names

let rec decls_of_elem = function
  | (_, SEdecl d) -> [d]
  | (_, SEmodule m) -> decls_of_module_expr m.ml_mod_expr
  | (_, SEmodtype _) -> []

and decls_of_module_expr = function
  | MEstruct (_, sel) -> List.concat_map decls_of_elem sel
  | MEfunctor _ -> []   (* 未適用の functor は捨てる (json.ml と同じ) *)
  | MEident _ | MEapply _ -> assert false

let render (m : Pycert_translate.pymodule) : Pp.t =
  let lines = Py_print.lines_of_module m in
  Pp.(v 0 (prlist_with_sep Common.fnl str lines) ++ Common.fnl ())

(** 全宣言を一度に翻訳する (fresh 変数のカウンタを 0 から通す) *)
let pp_struct (table : Common.State.t) (mls : ml_structure) : Pp.t =
  let mdecls =
    List.concat_map (fun (mp, sel) ->
      Common.State.with_visibility table mp [] (fun table ->
        List.concat_map (fun elem ->
          List.filter_map (Convert.conv_decl table) (decls_of_elem elem)) sel))
      mls
  in
  render (Pycert_translate.tr_prog 0 mdecls)

let pp_decl (table : Common.State.t) (d : ml_decl) : Pp.t =
  match Convert.conv_decl table d with
  | None -> Pp.mt ()
  | Some md -> render (Pycert_translate.tr_prog 0 [md])

let preamble _table (_mod_name : Id.t) (comment : Pp.t option) _used _usf : Pp.t =
  let c = match comment with
    | None -> Pp.mt ()
    | Some c -> Pp.(str "# " ++ hov 0 c ++ Common.fnl ())
  in
  Pp.(str "# Generated by Rocq extraction (rocq-python-plugin)." ++ Common.fnl () ++ c)

let python_descr : Common.State.t language_descr = {
  keywords = Id.Set.empty;   (* 識別子は g_ / v 接頭辞を付けるのでキーワードと衝突しない *)
  file_suffix = ".py";
  file_naming = (fun state mp -> Table.file_of_modfile (Common.State.get_table state) mp);
  preamble;
  pp_struct;
  sig_suffix = None;
  sig_preamble = (fun _ _ _ _ _ -> Pp.mt ());
  pp_sig = (fun _ _ -> Pp.mt ());
  pp_decl;
  unquote = (fun s -> s);
  upper_types = false;
  char_type = None;
  string_type = None;
  modular = false;   (* 単一ファイルのみ *)
  id_of_filename = (fun _ -> Id.of_string "Main");
}

let lang = Table.External "Python"

let () =
  if not (Common.is_registered_language lang) then
    Common.register_language lang python_descr
